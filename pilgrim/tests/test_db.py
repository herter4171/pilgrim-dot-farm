"""pilgrim.db: the SQLite-to-Postgres statement translation and the Row type
(SCALABILITY.md Step 2). Pure functions; no database."""
from __future__ import annotations

import pytest
from pilgrim import db
from pilgrim.db import DatabaseSettings, Row, split_script, translate_ddl, translate_sql


def test_placeholders_and_percent_literals():
    assert translate_sql("SELECT * FROM t WHERE a=? AND b=?") == \
        "SELECT * FROM t WHERE a=%s AND b=%s"
    # a LIKE literal must not become a psycopg format directive
    assert translate_sql("WHERE media_path LIKE '%.mp3' AND id=?") == \
        "WHERE media_path LIKE '%%.mp3' AND id=%s"
    assert translate_sql("LIKE '%\"request_id\"%'") == "LIKE '%%\"request_id\"%%'"


def test_ddl_types():
    ddl = translate_ddl("CREATE TABLE x (id INTEGER PRIMARY KEY AUTOINCREMENT, "
                        "started_at REAL, n INTEGER, really TEXT)")
    assert "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "started_at DOUBLE PRECISION" in ddl
    assert "really TEXT" in ddl          # \bREAL\b must not touch 'really'
    assert translate_sql("ALTER TABLE items ADD COLUMN art_attempted_at REAL") == \
        "ALTER TABLE items ADD COLUMN art_attempted_at DOUBLE PRECISION"
    assert "EXTRACT(EPOCH FROM now())" in translate_sql(
        "CREATE TABLE v (ip TEXT PRIMARY KEY, first_seen REAL NOT NULL "
        "DEFAULT (strftime('%s','now')))")
    # non-DDL statements are never type-rewritten
    assert translate_sql("UPDATE t SET note='REAL deal' WHERE id=?") == \
        "UPDATE t SET note='REAL deal' WHERE id=%s"


def test_split_script_drops_comment_lines():
    stmts = split_script("""
        -- a comment; with a semicolon
        CREATE TABLE a (x INTEGER);
        CREATE INDEX IF NOT EXISTS i ON a(x);

        DROP TABLE IF EXISTS b;
    """)
    assert stmts == ["CREATE TABLE a (x INTEGER)",
                     "CREATE INDEX IF NOT EXISTS i ON a(x)",
                     "DROP TABLE IF EXISTS b"]


def test_row_behaves_like_sqlite_row():
    r = Row({"id": 0, "title": 1}, (7, "Song"))
    assert r[0] == 7 and r["title"] == "Song"
    assert dict(r) == {"id": 7, "title": "Song"}
    a, b = r
    assert (a, b) == (7, "Song")
    assert r.get("missing") is None and r.get("id") == 7
    with pytest.raises(KeyError):
        r["nope"]


def test_database_settings_from_env(monkeypatch):
    monkeypatch.setenv("PILGRIM_ENV_FILE", "")
    for name in ("DATABASE_URL", "DATABASE_PASSWORD", "DB_PASS_SECRET_ARN"):
        monkeypatch.delenv(name, raising=False)   # pg-test mode sets these
    assert db.database_settings() is None
    monkeypatch.setenv("DATABASE_URL", "postgresql://pilgrim@db.example:5432/pilgrim")
    monkeypatch.setenv("DB_PASS_SECRET_ARN", "arn:aws:secretsmanager:us-west-1:1:secret:x")
    s = db.database_settings()
    assert s == DatabaseSettings("postgresql://pilgrim@db.example:5432/pilgrim", None,
                                 "arn:aws:secretsmanager:us-west-1:1:secret:x")
    assert s.host == "db.example"
    assert db._secret_region(s.secret_arn) == "us-west-1"
    monkeypatch.setenv("DATABASE_PASSWORD", "pw")
    assert db.resolve_password(db.database_settings()) == "pw"   # env wins, no AWS call


def test_open_store_is_sqlite_without_database_url(cfg, tmp_path, monkeypatch):
    monkeypatch.delenv("DATABASE_URL", raising=False)
    s = db.open_store(cfg, path=tmp_path / "x.db")
    assert s.dialect == "sqlite" and s.path == tmp_path / "x.db"
    s.close()


def test_store_dialect_matches_engine(tmp_env):
    _, store, _ = tmp_env
    import os
    expected = "postgres" if os.environ.get("PILGRIM_TEST_DATABASE_URL") else "sqlite"
    assert store.dialect == expected

DATABASE_PASSWORD_ENV = "DATABASE_PASSWORD"
DB_PASS_SECRET_ARN_ENV = "DB_PASS_SECRET_ARN"


# ------------------------------------------------------------------- rows
class Row(tuple):
    """A result row that behaves like `sqlite3.Row`: `r[0]`, `r["col"]`,
    `dict(r)`, `for (a, b) in rows`. psycopg builds these through
    `_row_factory`; SQLite keeps its native `sqlite3.Row`."""

    _index: dict[str, int]

    def __new__(cls, index: dict[str, int], values: Sequence[Any]) -> Row:
        self = super().__new__(cls, values)
        self._index = index
        return self

    def __getitem__(self, key):  # type: ignore[override]
        if isinstance(key, str):
            return tuple.__getitem__(self, self._index[key])
        return tuple.__getitem__(self, key)

    def keys(self) -> list[str]:
        return list(self._index)

    def get(self, key: str, default: Any = None) -> Any:
        pos = self._index.get(key)
        return default if pos is None else tuple.__getitem__(self, pos)


def _row_factory(cursor: Any) -> Callable[[Sequence[Any]], Row]:
    index = {d.name: i for i, d in enumerate(cursor.description or ())}
    return lambda values: Row(index, values)


# ------------------------------------------------------------ translation
_DDL_PREFIXES = ("CREATE", "ALTER ", "DROP T")


def translate_sql(sql: str) -> str:
    """SQLite-flavoured statement -> psycopg. `?` becomes `%s`; a literal `%`
    (LIKE patterns) is doubled so psycopg does not read it as a format
    directive. Store SQL never contains a literal `?`."""
    sql = sql.replace("%", "%%").replace("?", "%s")
    if sql.lstrip()[:6].upper() in _DDL_PREFIXES:
        sql = translate_ddl(sql)
    return sql


def translate_ddl(sql: str) -> str:
    """The SQLite DDL vocabulary `Store` uses, in Postgres terms. REAL is
    float4 in Postgres, which would truncate epoch seconds, hence DOUBLE
    PRECISION. `BY DEFAULT` identities accept the explicit ids the program
    splice and the migration copy insert."""
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT",
                      "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
    # strftime('%s','now') arrives here already %%-doubled by translate_sql,
    # or raw from executescript: accept both.
    sql = sql.replace("DEFAULT (strftime('%%s','now'))", "DEFAULT EXTRACT(EPOCH FROM now())")
    sql = sql.replace("DEFAULT (strftime('%s','now'))", "DEFAULT EXTRACT(EPOCH FROM now())")
    return sql


def split_script(script: str) -> list[str]:
    """Statements of a `;`-separated script, `--` comment lines removed."""
    lines = [ln for ln in script.splitlines() if not ln.strip().startswith("--")]
    return [s.strip() for s in "\n".join(lines).split(";") if s.strip()]


# ------------------------------------------------------------ connections
class Conn(Protocol):
    dialect: str
    IntegrityError: Any  # the engine's DB-API IntegrityError class

    def execute(self, sql: str, params: Sequence[Any] = ()) -> Any: ...
    def executemany(self, sql: str, rows: Iterable[Sequence[Any]]) -> None: ...
    def executescript(self, script: str) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def close(self) -> None: ...
    def released(self) -> None: ...
    def columns(self, table: str) -> set[str]: ...
    def tables(self) -> set[str]: ...
    def set_sequence_high(self, table: str, column: str, value: int) -> None: ...
    def sync_sequence(self, table: str, column: str) -> None: ...


class SqliteConn:
    """The engine `Store` was written against; everything passes straight
    through. `sqlite3.Row` gives the same row behaviour as `Row`."""

    dialect = "sqlite"
    IntegrityError = sqlite3.IntegrityError

    def __init__(self, path: Path) -> None:
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self._c = sqlite3.connect(str(self.path), check_same_thread=False)
        self._c.row_factory = sqlite3.Row
        self._c.execute("PRAGMA journal_mode=WAL")

    def execute(self, sql: str, params: Sequence[Any] = ()) -> sqlite3.Cursor:
        return self._c.execute(sql, params)

    def executemany(self, sql: str, rows: Iterable[Sequence[Any]]) -> None:
        self._c.executemany(sql, rows)

    def executescript(self, script: str) -> None:
        self._c.executescript(script)

    def commit(self) -> None:
        self._c.commit()

    def rollback(self) -> None:
        self._c.rollback()

    def close(self) -> None:
        self._c.close()

    def released(self) -> None:
        """Nothing to do: a SELECT never opens a transaction in sqlite3."""

    def columns(self, table: str) -> set[str]:
        return {r[1] for r in self._c.execute(f"PRAGMA table_info({table})")}

    def tables(self) -> set[str]:
        return {r[0] for r in self._c.execute(
            "SELECT name FROM sqlite_master WHERE type='table'")}

    def set_sequence_high(self, table: str, column: str, value: int) -> None:
        """Raise the AUTOINCREMENT high-water mark to at least `value`, so a
        renumbered seq is never handed out again (RADIO §5.3)."""
        r = self._c.execute(
            "SELECT seq FROM sqlite_sequence WHERE name=?", (table,)).fetchone()
        if r:
            self._c.execute("UPDATE sqlite_sequence SET seq=? WHERE name=?",
                            (max(int(r[0]), int(value)), table))
        else:
            self._c.execute("INSERT INTO sqlite_sequence (name, seq) VALUES (?, ?)",
                            (table, int(value)))

    def sync_sequence(self, table: str, column: str) -> None:
        """No-op: AUTOINCREMENT already tracks explicit inserts."""


_open_postgres: weakref.WeakSet[PostgresConn] = weakref.WeakSet()


class PostgresConn:
    """psycopg 3 connection speaking `Store`'s SQLite-flavoured SQL.

    Transactions: writes commit explicitly in `Store` (as they always did);
    a read leaves a transaction open in Postgres, so `released()` (called when
    the store lock is released) rolls that back rather than leaving the
    connection idle-in-transaction. A dropped connection (tailnet hiccup) is
    reopened once and the statement retried when no transaction was in flight;
    mid-transaction failures raise, and the caller's commit never happens.
    """

    dialect = "postgres"

    def __init__(self, dsn: str, password: str | None = None) -> None:
        import psycopg  # pinned in requirements.txt; absent in SQLite-only setups

        self._psycopg = psycopg
        self.IntegrityError = psycopg.IntegrityError
        self._dsn = dsn
        self._password = password
        self._c: Any = None
        self._connect()
        _open_postgres.add(self)

    def _connect(self) -> None:
        self._c = self._psycopg.connect(
            self._dsn, password=self._password, connect_timeout=10,
            autocommit=False, row_factory=_row_factory,
            application_name="pilgrim")

    def _idle(self) -> bool:
        from psycopg.pq import TransactionStatus
        return self._c.info.transaction_status == TransactionStatus.IDLE

    def execute(self, sql: str, params: Sequence[Any] = ()) -> Any:
        sql = translate_sql(sql)
        try:
            return self._c.execute(sql, params)
        except self._psycopg.OperationalError as e:
            if self._c.closed or self._idle():
                log.warning("db.reconnect", extra={"error": str(e)[:200]})
                self._connect()
                return self._c.execute(sql, params)
            raise

    def executemany(self, sql: str, rows: Iterable[Sequence[Any]]) -> None:
        with self._c.cursor() as cur:
            cur.executemany(translate_sql(sql), rows)

    def executescript(self, script: str) -> None:
        for stmt in split_script(script):
            self._c.execute(translate_sql(stmt))

    def commit(self) -> None:
        self._c.commit()

    def rollback(self) -> None:
        self._c.rollback()

    def close(self) -> None:
        if not self._c.closed:
            self._c.close()

    def released(self) -> None:
        if not self._c.closed and not self._idle():
            self._c.rollback()

    def columns(self, table: str) -> set[str]:
        rows = self._c.execute(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = %s", (table,)).fetchall()
        return {r[0] for r in rows}

    def tables(self) -> set[str]:
        rows = self._c.execute(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema = current_schema() AND table_type = 'BASE TABLE'").fetchall()
        return {r[0] for r in rows}

    def _sequence(self, table: str, column: str) -> tuple[str, int]:
        name = self._c.execute("SELECT pg_get_serial_sequence(%s, %s)",
                               (table, column)).fetchone()[0]
        last, called = self._c.execute(f"SELECT last_value, is_called FROM {name}").fetchone()
        return name, int(last) if called else int(last) - 1

    def set_sequence_high(self, table: str, column: str, value: int) -> None:
        name, current = self._sequence(table, column)
        self._c.execute("SELECT setval(%s, %s)", (name, max(current, int(value))))

    def sync_sequence(self, table: str, column: str) -> None:
        """After an explicit-id insert or renumber: Postgres identities do not
        follow explicit values (SQLite's AUTOINCREMENT does), so lift the
        sequence to the table's maximum or a later append would collide."""
        name, current = self._sequence(table, column)
        high = self._c.execute(f"SELECT COALESCE(MAX({column}), 0) FROM {table}").fetchone()[0]
        self._c.execute("SELECT setval(%s, %s)", (name, max(current, int(high))))


def close_all_postgres() -> int:
    """Close every live Postgres connection this process opened (test teardown
    before a schema reset; the station never calls it)."""
    n = 0
    for conn in list(_open_postgres):
        conn.close()
        n += 1
    return n


class StoreLock:
    """`threading.Lock` that tells the connection when it is released, so a
    read-only transaction never outlives the critical section."""

    def __init__(self, conn: Conn) -> None:
        self._lock = threading.Lock()
        self._conn = conn

    def __enter__(self) -> StoreLock:
        self._lock.acquire()
        return self

    def __exit__(self, *exc: object) -> None:
        try:
            self._conn.released()
        finally:
            self._lock.release()

    def acquire(self, blocking: bool = True, timeout: float = -1) -> bool:
        return self._lock.acquire(blocking, timeout)

    def release(self) -> None:
        self._conn.released()
        self._lock.release()

    def locked(self) -> bool:
        return self._lock.locked()


# -------------------------------------------------------------- selection
@dataclass(frozen=True)
class DatabaseSettings:
    url: str
    password: str | None
    secret_arn: str | None

    @property
    def host(self) -> str:
        return urlsplit(self.url).hostname or ""


def database_settings(env_file: Path | None = None) -> DatabaseSettings | None:
    """Postgres settings from the environment (or the `.env` fallback), or
    None when `DATABASE_URL` is unset: the SQLite file is then the store."""
    url = load_secret(DATABASE_URL_ENV, env_file)
    if not url:
        return None
    return DatabaseSettings(
        url=url,
        password=load_secret(DATABASE_PASSWORD_ENV, env_file) or None,
        secret_arn=load_secret(DB_PASS_SECRET_ARN_ENV, env_file) or None)


def _secret_region(arn: str) -> str | None:
    parts = arn.split(":")
    return parts[3] if len(parts) > 4 and parts[0] == "arn" else None


def resolve_password(settings: DatabaseSettings, profile: str | None = None) -> str | None:
    """`DATABASE_PASSWORD` wins; else read `DB_PASS_SECRET_ARN` from Secrets
    Manager with `profile` (the station's `media.aws_profile`) when that
    profile exists, else the default credential chain (a Fargate task role).
    The value is returned, never logged."""
    if settings.password:
        return settings.password
    if not settings.secret_arn:
        return None
    import boto3
    from botocore.exceptions import ProfileNotFound

    region = _secret_region(settings.secret_arn)
    try:
        session = boto3.Session(profile_name=profile or None, region_name=region)
    except ProfileNotFound:
        session = boto3.Session(region_name=region)
    body = session.client("secretsmanager").get_secret_value(
        SecretId=settings.secret_arn)["SecretString"]
    data = json.loads(body)
    password = data.get("password")
    if not isinstance(password, str) or not password:
        raise ValueError("DB secret has no `password` key")
    return password


def open_store(cfg: Config, *, path: Path | None = None) -> Store:
    """The station's store: Postgres when `DATABASE_URL` is set, else the
    SQLite file (`path`, default `library.db` under the package root)."""
    from pilgrim.store import Store

    settings = database_settings()
    if settings is None:
        return Store(path or (ROOT / cfg.library.db))
    password = resolve_password(settings, cfg.media.aws_profile)
    log.info("store.postgres", extra={"host": settings.host,
                                      "password_source": "env" if settings.password
                                      else ("secret" if settings.secret_arn else "none")})
    return Store(dsn=settings.url, password=password)


def env_summary() -> dict[str, Any]:
    """For the admin health payload: which engine, no secrets."""
    url = os.environ.get(DATABASE_URL_ENV, "")
    return {"engine": "postgres" if url else "sqlite",
            "host": urlsplit(url).hostname if url else None}

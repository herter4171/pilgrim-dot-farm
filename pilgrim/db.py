"""Database connections for `Store` (SCALABILITY.md Step 2; RADIO §14).

One `Store`, two engines. SQLite stays for `make test`, `make sim` and the
single-host dev run (AGENTS §1.2; operator decision, SCALABILITY §6).
PostgreSQL (RDS) is production: the station on the Mac writes to it over the
tailnet, the Fargate web tier reads and writes it inside the VPC.

`Store` writes every statement once, in the SQLite flavour it always had:
`?` placeholders, INTEGER flags, TEXT ISO timestamps, REAL epochs,
`INTEGER PRIMARY KEY AUTOINCREMENT` ids. `PostgresConn` rewrites the handful
of things that differ at execute time (placeholders, `%` literals, DDL
types, sequences), so the two engines cannot drift apart one statement at a
time. Anything SQL that would need a per-engine branch inside `Store` is a
bug here, not a feature there.

Engine selection is by environment (RADIO §12): `DATABASE_URL` set means
Postgres, with the password from `DATABASE_PASSWORD` or, more usually, from
the Secrets Manager secret named by `DB_PASS_SECRET_ARN` (JSON `username` /
`password`), read with the same AWS profile as media publishing
(`media.aws_profile`) or the default credential chain. Nothing here logs a
password or a URL that could carry one.
"""

#!/usr/bin/env bash
# Stateful half of the split on the Mac Studio (SPLIT_PLAN §8, RUNBOOK §5–6),
# native variant: Homebrew nginx gateway + the host's own Tailscale node,
# instead of the Docker gateway/compose.yaml.
#
#   tailnet :443 (tailscale serve) ─▶ gateway 127.0.0.1:8090 ─▶ origin 127.0.0.1:<station.port>
#
#   pilgrim/deploy/mac/origin.sh install    # render, install launchd units, serve
#   pilgrim/deploy/mac/origin.sh status
#   pilgrim/deploy/mac/origin.sh uninstall  # stop units, reset serve
#
# Secrets stay in the repo's gitignored .env (mode 600); this script never
# reads or prints them. Generated files live in $PILGRIM_ORIGIN_STATE.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
PY="$ROOT/.venv/bin/python"
STATE="${PILGRIM_ORIGIN_STATE:-$HOME/pilgrim-origin}"
LOGS="$HOME/Library/Logs/pilgrim"
AGENTS="$HOME/Library/LaunchAgents"
BREW="${BREW_PREFIX:-/opt/homebrew}"
NGINX="$BREW/bin/nginx"
TS="${TAILSCALE:-$(command -v tailscale || echo /usr/local/bin/tailscale)}"
GATEWAY_PORT="${GATEWAY_PORT:-8090}"
UID_=$(id -u)

# Origin public listener from config.yaml (hard rule 4: config is the source).
origin_hostport() {
    ( cd "$ROOT" && "$PY" -c 'from pathlib import Path; from pilgrim.config import load_config
c = load_config(Path("pilgrim/config.yaml")).station
print(f"{c.host}:{c.port}")' )
}

render_gateway() {
    local origin=$1 out="$STATE/gateway/nginx.conf"
    mkdir -p "$STATE/gateway" "$STATE/run" "$LOGS"
    cp "$ROOT/pilgrim/deploy/gateway/extra-none.conf" "$STATE/gateway/extra.conf"
    ( cd "$ROOT" && "$PY" -m pilgrim.tools.render_deploy \
        pilgrim/deploy/gateway/nginx.conf.template "$out.tmp" \
        --set GATEWAY_LISTEN="127.0.0.1:$GATEWAY_PORT" \
        --set ORIGIN_PUBLIC_HOSTPORT="$origin" \
        --set TRUSTED_EDGE_NET=127.0.0.1 \
        --set EXTRA_ALLOW_INCLUDE="$STATE/gateway/extra.conf" )
    # Container paths in the template -> Homebrew/user paths. nginx runs as
    # this user (no root), so drop the `user` directive.
    sed -e '/^user /d' \
        -e "s#/var/log/nginx/#$LOGS/gateway.#g" \
        -e "s#/var/run/nginx.pid#$STATE/run/gateway.pid#" \
        -e "s#/etc/nginx/mime.types#$BREW/etc/nginx/mime.types#" \
        "$out.tmp" > "$out"
    rm -f "$out.tmp"
    # Temp paths default under the Homebrew prefix; keep them in $STATE.
    "$NGINX" -t -c "$out" -p "$STATE/run/" -e "$LOGS/gateway.error.log"
}

write_wrapper() {
    mkdir -p "$STATE/bin"
    cat > "$STATE/bin/pilgrim-station" <<EOF
#!/bin/sh
# Generated by deploy/mac/origin.sh. Sources the gitignored .env (mode 600).
set -a
. "$ROOT/.env"
set +a
PATH="$BREW/bin:/usr/local/bin:/usr/bin:/bin:$ROOT/.venv/bin"
export PATH
cd "$ROOT"
exec "$PY" -m pilgrim.server
EOF
    chmod 755 "$STATE/bin/pilgrim-station"
}

plist() {  # label, program..., (stdout/err from label)
    local label=$1; shift
    local args=""
    for a in "$@"; do args="$args    <string>$a</string>
"; done
    cat > "$AGENTS/$label.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by pilgrim/deploy/mac/origin.sh. No secrets here. -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$label</string>
  <key>ProgramArguments</key>
  <array>
$args  </array>
  <key>WorkingDirectory</key><string>$ROOT</string>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>10</integer>
  <key>ProcessType</key><string>Interactive</string>
  <key>StandardOutPath</key><string>$LOGS/${label#farm.pilgrim.}.out.log</string>
  <key>StandardErrorPath</key><string>$LOGS/${label#farm.pilgrim.}.err.log</string>
</dict>
</plist>
EOF
}

load() {  # (re)load a LaunchAgent
    launchctl bootout "gui/$UID_/$1" 2>/dev/null || true
    launchctl bootstrap "gui/$UID_" "$AGENTS/$1.plist"
}

case "${1:-status}" in
install)
    [ -x "$PY" ] || { echo "error: no venv at $ROOT/.venv" >&2; exit 1; }
    [ -f "$ROOT/.env" ] || { echo "error: $ROOT/.env missing" >&2; exit 1; }
    [ -x "$NGINX" ] || { echo "error: brew install nginx" >&2; exit 1; }
    origin=$(origin_hostport)
    mkdir -p "$AGENTS" "$LOGS"
    render_gateway "$origin"
    write_wrapper
    plist farm.pilgrim.station "$STATE/bin/pilgrim-station"
    plist farm.pilgrim.gateway "$NGINX" -c "$STATE/gateway/nginx.conf" \
        -p "$STATE/run/" -e "$LOGS/gateway.error.log" -g "daemon off;"
    load farm.pilgrim.station
    load farm.pilgrim.gateway
    "$TS" serve --bg --https=443 "http://127.0.0.1:$GATEWAY_PORT"
    echo "origin up: tailnet:443 -> gateway 127.0.0.1:$GATEWAY_PORT -> origin $origin"
    ;;
status)
    launchctl list | grep -E 'farm\.pilgrim\.' || echo "no farm.pilgrim units"
    "$TS" serve status || true
    curl -s -m5 -o /dev/null -w "gateway /api/health %{http_code}\n" \
        "http://127.0.0.1:$GATEWAY_PORT/api/health" || true
    ;;
uninstall)
    "$TS" serve --https=443 off 2>/dev/null || true
    for l in farm.pilgrim.gateway farm.pilgrim.station; do
        launchctl bootout "gui/$UID_/$l" 2>/dev/null || true
    done
    ;;
*)
    echo "usage: $0 {install|status|uninstall}" >&2; exit 2
    ;;
esac

#!/usr/bin/env bash
# Interim single-host split (see compose.yaml): render the edge + gateway
# templates and run them next to the live origin on this host.
#
#   TRUSTED_PROXY_CIDR=172.31.0.0/16 pilgrim/deploy/interim/up.sh start
#   pilgrim/deploy/interim/up.sh stop | status
#
# Real client IP (behind Cloudflare → ALB): real_ip_header X-Forwarded-For with
# real_ip_recursive, trusting TRUSTED_PROXY_CIDR (the ALB's VPC) and every
# published Cloudflare range. A forged X-Forwarded-For sent straight to the ALB
# resolves to the sender's own IP, never the forged value.
#
# Split day (origin on the M5, gateway there behind Tailscale serve): re-run
#   LOCAL_GATEWAY=0 ORIGIN_SCHEME=https \
#   ORIGIN_HOST=pilgrim-origin.<tailnet>.ts.net ORIGIN_HOSTPORT=pilgrim-origin.<tailnet>.ts.net:443 \
#   MEDIA_CACHE_MAX=20g TRUSTED_PROXY_CIDR=... up.sh start
# which re-renders the edge against the M5 and removes the local gateway.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
PY="$ROOT/.venv/bin/python"
STATE="${PILGRIM_INTERIM_STATE:-$HOME/pilgrim-interim}"
COMPOSE="$ROOT/pilgrim/deploy/interim/compose.yaml"
EDGE_LISTEN="${EDGE_LISTEN:-0.0.0.0:8080}"
GATEWAY_PORT="${GATEWAY_PORT:-8090}"
ORIGIN_PUBLIC="${ORIGIN_PUBLIC:-127.0.0.1:5000}"   # the live pilgrim.server public listener
ORIGIN_SCHEME="${ORIGIN_SCHEME:-http}"
ORIGIN_HOSTPORT="${ORIGIN_HOSTPORT:-127.0.0.1:$GATEWAY_PORT}"
ORIGIN_HOST="${ORIGIN_HOST:-127.0.0.1}"
# Small while the origin shares this disk: caching media here only duplicates
# pilgrim/library/. Raise (e.g. 20g) once this host is edge-only.
MEDIA_CACHE_MAX="${MEDIA_CACHE_MAX:-100m}"
# 1 while the origin is on this host; 0 once the gateway runs on the M5.
LOCAL_GATEWAY="${LOCAL_GATEWAY:-1}"

dc() { docker compose -f "$COMPOSE" --env-file "$STATE/env" "$@"; }

cidr_ok() { [[ "$1" =~ ^[0-9a-fA-F:.]+/[0-9]{1,3}$ ]]; }

write_realip() {
    local out=$1 tmp
    tmp=$(mktemp)
    {
        echo "# Generated by interim/up.sh $(date -u +%FT%TZ). Do not edit."
        echo "real_ip_header    X-Forwarded-For;"
        echo "real_ip_recursive on;"
        echo "set_real_ip_from  $TRUSTED_PROXY_CIDR;   # ALB (VPC)"
        for fam in v4 v6; do
            curl -fsS -m 10 "https://www.cloudflare.com/ips-$fam" | while read -r c; do
                [ -z "$c" ] && continue
                cidr_ok "$c" || { echo "bad Cloudflare range: $c" >&2; exit 1; }
                echo "set_real_ip_from  $c;"
            done
        done
    } > "$tmp"
    [ "$(grep -c '^set_real_ip_from' "$tmp")" -ge 10 ] || {
        echo "error: Cloudflare range list looks empty" >&2; rm -f "$tmp"; exit 1; }
    mv "$tmp" "$out"
}

render() {
    mkdir -p "$STATE/cache/media" "$STATE/cache/micro" "$STATE/edge" "$STATE/gateway"
    write_realip "$STATE/realip.conf"
    cp "$ROOT/pilgrim/deploy/gateway/extra-none.conf" "$STATE/extra.conf"
    ( cd "$ROOT" && "$PY" -m pilgrim.tools.render_deploy \
        pilgrim/deploy/edge/nginx.conf.template "$STATE/edge/nginx.conf" \
        --set EDGE_LISTEN="$EDGE_LISTEN" \
        --set WEB_ROOT=/web \
        --set CACHE_DIR=/cache \
        --set MEDIA_CACHE_MAX="$MEDIA_CACHE_MAX" \
        --set ORIGIN_SCHEME="$ORIGIN_SCHEME" \
        --set ORIGIN_HOSTPORT="$ORIGIN_HOSTPORT" \
        --set ORIGIN_HOST="$ORIGIN_HOST" \
        --set REALIP_INCLUDE=/etc/nginx/realip.conf \
        --set CA_BUNDLE=/etc/ssl/certs/ca-certificates.crt \
        --set EXTRA_ALLOW_INCLUDE=/etc/nginx/extra.conf )
    ( cd "$ROOT" && "$PY" -m pilgrim.tools.render_deploy \
        pilgrim/deploy/gateway/nginx.conf.template "$STATE/gateway/nginx.conf" \
        --set GATEWAY_LISTEN="127.0.0.1:$GATEWAY_PORT" \
        --set ORIGIN_PUBLIC_HOSTPORT="$ORIGIN_PUBLIC" \
        --set TRUSTED_EDGE_NET=127.0.0.1 \
        --set EXTRA_ALLOW_INCLUDE=/etc/nginx/extra.conf )
    {
        echo "PILGRIM_EDGE_CONF=$STATE/edge/nginx.conf"
        echo "PILGRIM_GATEWAY_CONF=$STATE/gateway/nginx.conf"
        echo "PILGRIM_REALIP_CONF=$STATE/realip.conf"
        echo "PILGRIM_EXTRA_CONF=$STATE/extra.conf"
        echo "PILGRIM_WEB_ROOT=$ROOT/pilgrim/web"
        echo "PILGRIM_CACHE_DIR=$STATE/cache"
        echo "PILGRIM_UID=$(id -u)"
        echo "PILGRIM_GID=$(id -g)"
    } > "$STATE/env"
}

case "${1:-start}" in
start)
    if [ -z "${TRUSTED_PROXY_CIDR:-}" ]; then   # default: this instance's VPC (IMDSv2)
        tok=$(curl -fsS -m 2 -X PUT http://169.254.169.254/latest/api/token \
              -H 'X-aws-ec2-metadata-token-ttl-seconds: 60' || true)
        mac=$(curl -fsS -m 2 -H "X-aws-ec2-metadata-token: $tok" \
              http://169.254.169.254/latest/meta-data/mac || true)
        TRUSTED_PROXY_CIDR=$(curl -fsS -m 2 -H "X-aws-ec2-metadata-token: $tok" \
              "http://169.254.169.254/latest/meta-data/network/interfaces/macs/$mac/vpc-ipv4-cidr-block" || true)
    fi
    : "${TRUSTED_PROXY_CIDR:?not on EC2: set TRUSTED_PROXY_CIDR to the VPC CIDR of the ALB}"
    cidr_ok "$TRUSTED_PROXY_CIDR" || { echo "error: TRUSTED_PROXY_CIDR=$TRUSTED_PROXY_CIDR" >&2; exit 2; }
    render
    case "$LOCAL_GATEWAY" in
    1) dc up -d --force-recreate ;;
    0) dc up -d --force-recreate edge && dc rm -sf gateway ;;
    *) echo "error: LOCAL_GATEWAY=$LOCAL_GATEWAY (0|1)" >&2; exit 2 ;;
    esac
    for _ in $(seq 1 50); do
        curl -sf "http://127.0.0.1:${EDGE_LISTEN##*:}/edge-health" >/dev/null && break
        sleep 0.2
    done
    curl -sf "http://127.0.0.1:${EDGE_LISTEN##*:}/edge-health" >/dev/null || {
        echo "error: edge did not come up" >&2; dc logs --tail 40 >&2; exit 1; }
    if [ "$LOCAL_GATEWAY" = 1 ]; then
        echo "split up: edge=$EDGE_LISTEN -> gateway=127.0.0.1:$GATEWAY_PORT -> origin=$ORIGIN_PUBLIC"
    else
        echo "split up: edge=$EDGE_LISTEN -> $ORIGIN_SCHEME://$ORIGIN_HOSTPORT (no local gateway)"
    fi
    ;;
stop)
    [ -f "$STATE/env" ] && dc down --remove-orphans
    ;;
status)
    [ -f "$STATE/env" ] && dc ps
    ;;
*)
    echo "usage: $0 {start|stop|status}" >&2; exit 2
    ;;
esac
